def rank(xp):
    return next(name for threshold, name in reversed(RANKS) if xp >= threshold)

def badges(user, owned):
    result = []
    if user['streak'] >= 7: result.append('🗓 Свой в Логове')
    if user['wins'] >= 10: result.append('⚔️ Дворовый чемпион')
    if user['correct'] >= 20: result.append('🧠 Подозрительно умный')
    if user['care'] >= 20: result.append('🥣 Кормилец мрази')
    if len(owned) >= 4: result.append('🎩 Коллекционер тряпья')
    return result
